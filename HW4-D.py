# 讀取輸入的停車小時數 h
h = int(input())

# 依據小時數分段計算累進停車費
if h <= 2:
    # 第 1～2 小時：每小時 30 元
    total_fee = h * 30
elif h <= 5:
    # 前 2 小時 (60 元) + 第 3～5 小時 (每小時 20 元)
    total_fee = 60 + (h - 2) * 20
else:
    # 前 2 小時 (60 元) + 第 3～5 小時 (60 元) + 第 6 小時起 (每小時 10 元)
    total_fee = 120 + (h - 5) * 10

# 輸出總停車費金額
print(total_fee)